"""安装程序「内嵌 Python + 解释器选择」链路的静态判据（CI / 无 GUI 也能跑）。

守什么：
  1. .iss 真的用了 Inno 标准向导页（单选 + 文件浏览），不是 bat 让用户自己填；
  2. 安装器写出的 python_env.txt 与 setup_env.py 的 write_pointer 同格式
     （三方同读一份真相），且内嵌解释器写的是相对路径；
  3. Go launcher 会把仓库内相对指针按 root 还原；
  4. runtime 是**构建产物**：不进源码白名单、不算源码文件。

为什么静态判据：runtime 是几百 MB 的构建产物，只在打包机上有；
CI 干净 checkout 不该有它。所以这里查的是"承诺与协议"，不是 runtime 本身。
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ISS = ROOT / "installer" / "sphere_motion.iss"
GO = ROOT / "native" / "launcher" / "main.go"
SETUP_ENV = ROOT / "apps" / "setup_env.py"
BUNDLE = ROOT / "apps" / "tools" / "make_clean_bundle.py"
GITIGNORE = ROOT / ".gitignore"


def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return ""


def main() -> int:
    checks: list[tuple[str, bool]] = []
    iss = _read(ISS)
    go = _read(GO)
    setup = _read(SETUP_ENV)
    bundle = _read(BUNDLE)
    gi = _read(GITIGNORE)

    # 1. 标准 Windows 向导页（不是 bat 交互）
    checks.append((".iss 用 CreateInputOptionPage 做解释器单选",
                   "CreateInputOptionPage" in iss))
    checks.append((".iss 用 CreateInputFilePage 浏览选 python.exe",
                   "CreateInputFilePage" in iss))
    checks.append((".iss 按选择跳过路径页（ShouldSkipPage）",
                   "ShouldSkipPage" in iss and "PathPage.ID" in iss))
    checks.append((".iss 校验所选解释器能 import cv2/numpy",
                   "import cv2, numpy" in iss))
    checks.append((".iss 运行时按选择装（Check: WantBundledPython）",
                   "WantBundledPython" in iss and "runtime\\*" in iss))
    checks.append((".iss 卸载清掉 runtime 与指针",
                   "filesandordirs; Name: \"{app}\\runtime\"" in iss
                   and "python_env.txt" in iss))

    # 2. 写指针协议与 setup_env.py 一致
    for key in ("python=", "kind=", "created=", "python_version=", "verified="):
        checks.append((f".iss 写指针含 {key}", f"lines.Add('{key}" in iss))
    checks.append((".iss 内嵌解释器写相对路径（换机仍指对）",
                   "runtime/python/python.exe" in iss))
    checks.append(("setup_env.py 用同一指针格式",
                   "sphere-python-env v1" in setup and "def write_pointer" in setup))
    checks.append(("setup_env.py 仓库内写相对路径",
                   "relative_to(root.resolve())" in setup))

    # 2b. 真的把安装器格式文本喂给 parse_pointer，验证三方协议（纯函数，无 IO）
    try:
        sys.path.insert(0, str(ROOT / "apps"))
        import setup_env as se  # type: ignore
        fake_root = ROOT / "fake_app"
        parsed = se.parse_pointer(
            "# sphere-python-env v1 - generated by installer; do not edit\n"
            "python=runtime/python/python.exe\n"
            "kind=bundled\n"
            "created=by-installer\n",
            fake_root)
        checks.append(("parse_pointer 跳过 # 注释并解析 python= 行",
                       parsed == (fake_root / "runtime/python/python.exe").resolve()))
        parsed_abs = se.parse_pointer(
            "python=C:\\Python314\\python.exe\n", fake_root)
        checks.append(("parse_pointer 绝对路径原样返回",
                       parsed_abs is not None and parsed_abs.is_absolute()))
    except Exception as exc:  # 无 GUI/依赖也应能导入；导入失败就是回归
        checks.append((f"setup_env 可导入并解析指针（{exc}）", False))

    # 3. Go launcher 还原相对指针
    checks.append(("launcher 把相对 python= 按 root 还原",
                   "filepath.IsAbs(v)" in go and "filepath.Join(root, filepath.FromSlash(v))" in go))

    # 4. runtime 是产物，不进源码白名单
    checks.append(("内嵌 runtime 不进源码包白名单",
                   "runtime" not in bundle and "release_stage" not in bundle))
    checks.append(("产物目录被 git 忽略（非源码）",
                   "outputs/" in gi))

    bad = [name for name, ok in checks if not ok]
    for name, ok in checks:
        print(("  OK   " if ok else "  FAIL ") + name)
    print(f"判定结果：{'全部通过' if not bad else '有不达标项 ' + str(len(bad))}")
    print("=" * 70)
    for b in bad:
        print("  FAIL", b)
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
