def iter_items():
    """遍历所有 (分区 id, 分区标题, 条目标题, 正文)。"""
    for sid, stitle, items in SECTIONS:
        for title, body in items:
            yield sid, stitle, title, body


def search(keyword: str) -> list[tuple[str, str, str, str]]:
    """按关键词搜标题 + 正文（不区分大小写），返回匹配的条目。

    多个词用空格分开时是**与**关系 —— 搜「采样 坐标」只留同时含这两个词的条目，
    这样在几十条说明里定位更快。空关键词返回空（不返回全部，避免列表太长）。
    """
    words = [w for w in keyword.lower().split() if w]
    if not words:
        return []
    hits = []
    for sid, stitle, title, body in iter_items():
        hay = (title + "\n" + body).lower()
        if all(w in hay for w in words):
            hits.append((sid, stitle, title, body))
    return hits
